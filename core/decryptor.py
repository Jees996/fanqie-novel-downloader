# 兼容需求文档中的「十进制字符串键」写法，便于外部脚本直接复用
FONT_MAP_DECIMAL: dict[str, str] = {str(k): v for k, v in FONT_MAP.items()}


def is_pua(char: str) -> bool:
    """判断单个字符是否落在 Unicode 私有区。"""
    return len(char) == 1 and PUA_START <= ord(char) <= PUA_END


def decrypt_text(text: str) -> str:
    """把包含 PUA 混淆字符的文本还原为可读明文。

    未命中的字符（正常中文、标点、换行等）原样保留，保证幂等：对已解密的
    文本再次调用不会产生副作用。
    """
    if not text:
        return ""
    if not PUA_RE.search(text):
        return text
    return "".join(FONT_MAP.get(ord(ch), ch) for ch in text)


def has_obfuscation(text: str) -> bool:
    """文本中是否仍含有 PUA 混淆字符。"""
    return bool(text) and bool(PUA_RE.search(text))


def remaining_pua(text: str) -> list[str]:
    """返回文本中仍未映射的 PUA 字符（去重、按出现顺序）。"""
    seen: list[str] = []
    for ch in text:
        if is_pua(ch) and ch not in seen:
            seen.append(ch)
    return seen


def register_font_map(mapping: dict[int, str]) -> None:
    """注册 / 覆盖额外的字体映射。

    当番茄更新 ``awesome-font`` 版本（字体文件名 hash 变化）时，可在运行时
    先抓取新字体做比对，再把增量映射注册进来，无需改代码。
    """
    for codepoint, char in mapping.items():
        if PUA_START <= int(codepoint) <= PUA_END:
            FONT_MAP[int(codepoint)] = char
    FONT_MAP_DECIMAL.clear()
    FONT_MAP_DECIMAL.update({str(k): v for k, v in FONT_MAP.items()})


