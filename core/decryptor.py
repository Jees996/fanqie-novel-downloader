"""番茄小说动态字体（awesome-font）逆向解密内核。

原理
----
PC 端 reader 页面使用字节跳动自建的 ``awesome-font`` 子集字体，把高频汉字 /
数字 / 字母的 Unicode 码点重映射到私有区（PUA，U+E000 - U+F8FF）。页面 HTML
里拿到的是 PUA 字符，浏览器靠该字体渲染出正常字形；直接抓取 HTML 得到的是
乱码，必须把 PUA 码点洗回真实字符。

映射来源与可信度
----------------
* 线上字体文件固定为 ``awesome-font/c/dc027189e0ba4cd.woff2``（全局同一份，
  与书籍、章节无关），共 362 个 PUA 字形。
* 本表通过「落地页明文前 10 章 × PC reader 混淆正文」逐字符对齐得到 ground
  truth（5 本书、291 组无冲突配对），再与字体字形轮廓交叉校验补全，362 项
  全部覆盖，实测解码后 PUA 残留为 0。
* 原需求文档中的示例表存在少量错位（例如 58406 实为「命」而非「到」），
  以本表为准。

用法
----
>>> from core.decryptor import decrypt_text
>>> decrypt_text("\ue423乾皇朝")   # doctest: +SKIP
'大乾皇朝'
"""

